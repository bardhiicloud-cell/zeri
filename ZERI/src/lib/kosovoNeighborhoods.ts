/**
 * Returns all available neighborhoods for a municipality, merging
 * the standard dictionary with any registered neighborhoods from reports.
 */
export function getMunicipalNeighborhoods(municipality: string, reports: any[] = []): string[] {
  if (!municipality) return [];
  const base = ALL_KOSOVO_MUNICIPALITY_NEIGHBORHOODS[municipality] || ["Qendra", "Lagja e Re", "Fshatrat"];
  
  const fromReports = reports
    .filter(r => {
      const m = r?.municipality || r?.location?.municipality;
      return m === municipality;
    })
    .map(r => r?.neighborhood || r?.location?.neighborhood || r?.location?.districtMapId)
    .filter(Boolean) as string[];

  const unique = Array.from(new Set([...base, ...fromReports]));
  return unique.sort((a, b) => a.localeCompare(b, 'sq'));
}
